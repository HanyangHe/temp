function rankings = collect_candidate_rankings_local(pyResult, fieldName)
    % MATLAB struct-array assignment requires every element to have exactly
    % the same field set and field order.  The JSON candidate rows may omit
    % optional PySR metadata such as loss or score on individual equations,
    % so assigning the decoded rows directly can raise:
    %   "Subscripted assignment between dissimilar structures."
    % Normalize every row into one fixed schema before appending it.
    template = candidate_ranking_template_local();
    rankings = repmat(template, 1, 0);
    if ~isstruct(pyResult) || ~isfield(pyResult, 'outputs') || ~isstruct(pyResult.outputs)
        return;
    end
    outs = pyResult.outputs;
    for i = 1:numel(outs)
        rows = getfield_default_local(outs(i), fieldName, struct([]));
        outputIndex = getfield_default_local(outs(i), 'output_index', i);
        if isstruct(rows)
            for j = 1:numel(rows)
                rankings(end+1) = normalize_candidate_ranking_row_local(rows(j), outputIndex); %#ok<AGROW>
            end
        elseif iscell(rows)
            % Defensive path for MATLAB releases that decode heterogeneous
            % JSON object arrays as cell arrays rather than struct arrays.
            for j = 1:numel(rows)
                if isstruct(rows{j})
                    rankings(end+1) = normalize_candidate_ranking_row_local(rows{j}, outputIndex); %#ok<AGROW>
                end
            end
        end
    end
end

