function out = normalize_string_cell_local(value)
%NORMALIZE_STRING_CELL_LOCAL Convert char/string/cell input to a row cellstr.
    if isempty(value)
        out = {};
    elseif ischar(value)
        out = {value};
    elseif isstring(value)
        out = cellstr(value(:).');
    elseif iscell(value)
        out = cellfun(@(x) char(string(x)), value(:).', 'UniformOutput', false);
        out = out(~cellfun(@isempty, strtrim(out)));
    else
        error('Initial PySR guesses must be char, string, or cell array of strings.');
    end
end

function val = getfield_default_local(s, name, defaultVal)
    if isstruct(s) && isfield(s, name) && ~isempty(s.(name))
        val = s.(name);
    else
        val = defaultVal;
    end
end


function cmd = format_command_for_display_local(pythonExe, guardPath, guardArgs)
    parts = [{pythonExe}, {guardPath}, guardArgs];
    for k = 1:numel(parts)
        value = char(parts{k});
        value = strrep(value, '"', '\"');
        parts{k} = ['"', value, '"'];
    end
    cmd = strjoin(parts, ' ');
end

