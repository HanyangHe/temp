function expr = collect_expressions_local(pyResult)
    expr = '';
    if isstruct(pyResult) && isfield(pyResult, 'outputs')
        outs = pyResult.outputs;
        if isstruct(outs)
            parts = cell(1, numel(outs));
            for i = 1:numel(outs)
                if isfield(outs(i), 'expression')
                    parts{i} = char(outs(i).expression);
                else
                    parts{i} = '';
                end
            end
            if numel(parts) == 1
                expr = parts{1};
            else
                labeled = cell(1, numel(parts));
                for i = 1:numel(parts)
                    labeled{i} = sprintf('y%d = %s', i, parts{i});
                end
                expr = strjoin(labeled, '; ');
            end
        end
    end
end


function topExpr = collect_top_expressions_local(pyResult, fieldName)
    topExpr = struct([]);
    if nargin < 2 || isempty(fieldName)
        fieldName = 'top_expressions';
    end
    if ~isstruct(pyResult) || ~isfield(pyResult, 'outputs')
        return;
    end
    outs = pyResult.outputs;
    if ~isstruct(outs)
        return;
    end
    iRow = 0;
    for i = 1:numel(outs)
        if ~isfield(outs(i), fieldName) || isempty(outs(i).(fieldName))
            continue;
        end
        rows = outs(i).(fieldName);
        if ~isstruct(rows)
            continue;
        end
        for j = 1:numel(rows)
            iRow = iRow + 1;
            topExpr(iRow).outputIndex = getfield_default_local(outs(i), 'output_index', i); %#ok<AGROW>
            topExpr(iRow).rank = getfield_default_local(rows(j), 'rank', j);
            topExpr(iRow).complexity = getfield_default_local(rows(j), 'complexity', NaN);
            topExpr(iRow).loss = getfield_default_local(rows(j), 'loss', NaN);
            topExpr(iRow).score = getfield_default_local(rows(j), 'score', NaN);
            if isfield(rows(j), 'expression') && ~isempty(rows(j).expression)
                topExpr(iRow).expression = char(rows(j).expression);
            else
                topExpr(iRow).expression = '<expression unavailable>';
            end
        end
    end
end

